/// Whether `host`, as the URL parser gives it, is one of GitHub's log hosts.
pub(crate) fn log_host(host: &str) -> Option<&'static str> {
    BLOB_HOSTS
        .iter()
        .chain(PIPELINES_HOSTS.iter())
        .find(|listed| **listed == host)
        .copied()
}

/// Every log host, as the broker looks them up at its start.
pub(crate) fn log_hosts() -> impl Iterator<Item = &'static str> {
    BLOB_HOSTS.iter().chain(PIPELINES_HOSTS.iter()).copied()
}
