//! Typed launcher operation on the existing authenticated runtime channel.
//! Deliberately absent from `respond`: HTTP ingress cannot choose a recipient
//! or turn an arbitrary request into a raw application-secret read operation.

use codewire_workload_secrets::{
    EnvironmentProjection, MAX_SEALED_ENVIRONMENT_PROJECTION_BYTES, ProjectionContext,
    ProjectionRecipient, validate_projection_recipient,
};

use super::*;

pub(super) struct PendingProjection {
    pub epoch: u64,
    // None is a cancelled tombstone; count it until response or epoch loss so
    // cancelled blocking authority operations cannot evade the shared bound.
    pub response: Option<oneshot::Sender<Result<Vec<u8>, BridgeFailure>>>,
}

/// Ciphertext and a short-lived authority fence; never owns plaintext or a
/// recipient private key. Revalidate after the final launcher reports ready.
pub struct RelayedEnvironmentProjection {
    ciphertext: Vec<u8>,
    bridge: CredentialBridge,
    epoch: u64,
    context: ProjectionContext,
}

impl RelayedEnvironmentProjection {
    pub fn ciphertext(&self) -> &[u8] {
        &self.ciphertext
    }

    pub async fn validate(&self) -> Result<(), Status> {
        self.context
            .validate_at(now_unix_ms()?)
            .map_err(|_| invalid_projection_context())?;
        require_active_epoch(&*self.bridge.inner.lock().await, self.epoch)
    }
}

impl CredentialBridge {
    /// Hold an initial trusted startup launch until the host's authenticated
    /// connection has been activated. Socket readiness alone is not admission.
    /// This never retries a request or waits for a disconnected host to return;
    /// the original launch deadline still bounds all subsequent work.
    pub async fn wait_for_initial_host(&self, context: &ProjectionContext) -> Result<(), Status> {
        context
            .validate_at(now_unix_ms()?)
            .map_err(|_| invalid_projection_context())?;
        let identity = self.identity();
        if context.environment_id != *identity.environment_id.as_bytes()
            || context.operation_generation != identity.environment_generation
        {
            return Err(invalid_projection_context());
        }
        let remaining = context
            .deadline_unix_ms
            .checked_sub(now_unix_ms()?)
            .filter(|remaining| *remaining > 0)
            .ok_or_else(invalid_projection_context)?;
        let deadline = tokio::time::Instant::now() + Duration::from_millis(remaining);
        loop {
            // Register before observing state so concurrent activation cannot
            // lose a wake-up. notify_waiters wakes every startup waiter.
            let admitted = self.host_admitted.notified();
            tokio::pin!(admitted);
            admitted.as_mut().enable();
            {
                let state = self.inner.lock().await;
                context
                    .validate_at(now_unix_ms()?)
                    .map_err(|_| invalid_projection_context())?;
                if state.active.is_some() {
                    return Ok(());
                }
                if state.next_epoch != 0 {
                    return Err(projection_unavailable());
                }
            }
            tokio::time::timeout_at(deadline, admitted)
                .await
                .map_err(|_| projection_unavailable())?;
        }
    }

    /// Request only this environment's already-selected values at an actual
    /// launcher. The application HTTP ingress does not expose this method.
    /// Callers recheck lifecycle authority after resolution and before exec.
    pub async fn project_environment(
        &self,
        context: ProjectionContext,
    ) -> Result<EnvironmentProjection, Status> {
        let recipient = ProjectionRecipient::new();
        let encrypted = self
            .project_environment_for_recipient(context.clone(), recipient.public_key())
            .await?;
        recipient
            .open(encrypted.ciphertext(), &context, now_unix_ms()?)
            .map_err(|_| {
                Status::failed_precondition("environment projection response is invalid or expired")
            })
    }

    /// Relay ciphertext to a recipient generated by the actual final launcher.
    /// This transport owns no recipient private key and cannot open the result.
    /// Only the authenticated, exact-process launch rendezvous may call it;
    /// it is deliberately not an application HTTP operation.
    pub async fn project_environment_for_recipient(
        &self,
        context: ProjectionContext,
        recipient_public_key: [u8; 32],
    ) -> Result<RelayedEnvironmentProjection, Status> {
        context
            .validate_at(now_unix_ms()?)
            .map_err(|_| invalid_projection_context())?;
        validate_projection_recipient(recipient_public_key)
            .map_err(|_| invalid_projection_context())?;
        let identity = self.identity();
        if context.environment_id != *identity.environment_id.as_bytes()
            || context.operation_generation != identity.environment_generation
        {
            return Err(invalid_projection_context());
        }
        let request_id = Uuid::new_v4().to_string();
        let (response_tx, response_rx) = oneshot::channel();
        let (epoch, output) = {
            let state = self.inner.lock().await;
            let active = state.active.as_ref().ok_or_else(projection_unavailable)?;
            if state.in_flight() >= CREDENTIAL_BRIDGE_MAX_IN_FLIGHT {
                return Err(Status::resource_exhausted(
                    "environment projection request limit reached",
                ));
            }
            let epoch = active.epoch;
            let output = active.output.clone();
            (epoch, output)
        };
        let request = v1::EnvironmentProjectionRequest {
            request_id: request_id.clone(),
            recipient_public_key: recipient_public_key.to_vec(),
            selection_sha256: context.selection_sha256.to_vec(),
            deadline_unix_ms: context.deadline_unix_ms,
            local_inventories: Vec::new(),
        };
        let remaining = context
            .deadline_unix_ms
            .checked_sub(now_unix_ms()?)
            .filter(|remaining| *remaining > 0)
            .ok_or_else(invalid_projection_context)?;
        let deadline = tokio::time::Instant::now() + Duration::from_millis(remaining);
        // Reserve before registration. Cancellation while waiting for a full
        // output queue must not leave a tombstone for a request never sent.
        let permit = tokio::time::timeout_at(
            deadline.min(tokio::time::Instant::now() + HOST_SEND_TIMEOUT),
            output.reserve_owned(),
        )
        .await
        .map_err(|_| projection_unavailable())?
        .map_err(|_| projection_unavailable())?;
        {
            let mut state = self.inner.lock().await;
            require_active_epoch(&state, epoch)?;
            context
                .validate_at(now_unix_ms()?)
                .map_err(|_| invalid_projection_context())?;
            if state.in_flight() >= CREDENTIAL_BRIDGE_MAX_IN_FLIGHT
                || state.contains_request(&request_id)
            {
                return Err(Status::resource_exhausted(
                    "environment projection request limit reached",
                ));
            }
            state.projections.insert(
                request_id.clone(),
                PendingProjection {
                    epoch,
                    response: Some(response_tx),
                },
            );
            // No suspension between registration and dispatch. Epoch replacement
            // cannot interleave until its state lock is released.
            permit.send(Ok(guest_message(
                v1::credential_bridge_guest_message::Payload::EnvironmentProjection(request),
            )));
        }
        let mut cancellation = PendingCancellation::new(self.clone(), request_id.clone(), epoch);
        let encrypted = match tokio::time::timeout_at(deadline, response_rx).await {
            Ok(Ok(Ok(encrypted))) => encrypted,
            Ok(Ok(Err(BridgeFailure::Denied))) => {
                return Err(Status::permission_denied("environment projection denied"));
            }
            Ok(Ok(Err(BridgeFailure::TooLarge))) => {
                return Err(Status::resource_exhausted(
                    "environment projection exceeds limits",
                ));
            }
            Ok(Ok(Err(_))) | Ok(Err(_)) => return Err(projection_unavailable()),
            Err(_) => {
                self.cancel(&request_id, epoch).await;
                cancellation.disarm();
                return Err(Status::deadline_exceeded("environment projection expired"));
            }
        };
        cancellation.disarm();
        context
            .validate_at(now_unix_ms()?)
            .map_err(|_| invalid_projection_context())?;
        // Strict, like `validate`: ciphertext answered on a draining epoch is
        // not released, since its fence could never validate afterwards.
        require_active_epoch(&*self.inner.lock().await, epoch)?;
        Ok(RelayedEnvironmentProjection {
            ciphertext: encrypted,
            bridge: self.clone(),
            epoch,
            context,
        })
    }

    pub(super) async fn apply_projection_response(
        &self,
        epoch: u64,
        response: v1::EnvironmentProjectionResponse,
    ) -> Result<(), Status> {
        use v1::environment_projection_response::Result as ProjectionResult;
        let result = match response.result {
            // The codec applies the exact framing bound before decrypting; this
            // outer conservative bound prevents retaining oversized wire data.
            Some(ProjectionResult::SealedProjection(bytes))
                if !bytes.is_empty() && bytes.len() <= MAX_SEALED_ENVIRONMENT_PROJECTION_BYTES =>
            {
                Ok(bytes)
            }
            Some(ProjectionResult::Failure(reason)) => {
                Err(match v1::CredentialBridgeFailureReason::try_from(reason) {
                    Ok(v1::CredentialBridgeFailureReason::Denied) => BridgeFailure::Denied,
                    Ok(v1::CredentialBridgeFailureReason::Unavailable) => {
                        BridgeFailure::Unavailable
                    }
                    Ok(v1::CredentialBridgeFailureReason::ResponseTooLarge) => {
                        BridgeFailure::TooLarge
                    }
                    _ => return Err(invalid_host_frame()),
                })
            }
            _ => return Err(invalid_host_frame()),
        };
        let pending = {
            let mut state = self.inner.lock().await;
            require_live_epoch(&state, epoch)?;
            take_registered(&mut state.projections, &response.request_id, |pending| {
                pending.epoch == epoch
            })?
        };
        if let Some(sender) = pending.response {
            // Caller cancellation is normal; it does not invalidate other
            // requests sharing this authenticated bridge epoch.
            let _ = sender.send(result);
        }
        Ok(())
    }
}

pub(super) fn take_projections(state: &mut BridgeState, epoch: u64) -> Vec<PendingProjection> {
    let ids: Vec<_> = state
        .projections
        .iter()
        .filter(|(_, pending)| pending.epoch == epoch)
        .map(|(id, _)| id.clone())
        .collect();
    ids.into_iter()
        .filter_map(|id| state.projections.remove(&id))
        .collect()
}

pub(super) fn fail_projections(pending: Vec<PendingProjection>) {
    for request in pending {
        if let Some(sender) = request.response {
            let _ = sender.send(Err(BridgeFailure::Unavailable));
        }
    }
}

fn now_unix_ms() -> Result<u64, Status> {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .ok()
        .and_then(|duration| u64::try_from(duration.as_millis()).ok())
        .ok_or_else(projection_unavailable)
}

fn invalid_projection_context() -> Status {
    Status::invalid_argument("environment projection context is invalid or expired")
}

fn projection_unavailable() -> Status {
    Status::unavailable("environment projection authority is unavailable")
}

