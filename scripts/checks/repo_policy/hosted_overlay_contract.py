# Generated by a configMapGenerator, so rendered with a content hash suffix.
GENERATED_CONFIG_MAPS = ("codewire-config", "codewire-dashboard-public-config")

SENTINEL = "hosted-overlay-contract"


def pinned(path: str, value: Any) -> dict[str, Any]:
    """The value a hosted patch rewrites, or the peer it selects by index."""
    return {"op": "test", "path": path, "value": value}


def replaced(path: str) -> dict[str, Any]:
    """A path a hosted patch replaces, which must exist.

    Kustomize's JSON-patch replace adds a missing final key instead of failing,
    so a renamed source key would leave the hosted value on a dead key. A
    remove fails when the path is missing.
    """
    return {"op": "remove", "path": path}


def added(path: str) -> dict[str, Any]:
    """A key a hosted patch adds; the add fails if its parent is missing."""
    return {"op": "add", "path": path, "value": SENTINEL}


def container(name: str) -> dict[str, Any]:
    # Strategic merge patches select a container by name; a renamed container
    # would gain a second, image-less container instead.
    return pinned("/spec/template/spec/containers/0/name", name)


def ingress(host: str, secret: str) -> tuple[dict[str, Any], ...]:
    return (
        pinned("/spec/tls/0/hosts/0", host),
        pinned("/spec/tls/0/secretName", secret),
        pinned("/spec/rules/0/host", host),
    )


def sandbox_role(kind: str, name: str, subject: str | None = None) -> tuple[str, str, tuple[dict[str, Any], ...]]:
    ops = [pinned("/metadata/namespace", "prod-sandboxes")]
    if subject is not None:
        ops.append(pinned("/subjects/0", {"kind": "ServiceAccount", "name": subject, "namespace": "prod"}))
    return (kind, name, tuple(ops))


def peer(namespace: str, labels: dict[str, str]) -> dict[str, Any]:
    return {
        "namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": namespace}},
        "podSelector": {"matchLabels": labels},
    }


