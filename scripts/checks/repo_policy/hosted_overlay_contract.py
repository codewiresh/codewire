"""The source resources the hosted overlays patch (codewire#3189).

The hosted Dev and Production overlays live in the private codewire/deploy
repository, under hosted/deployments/k8s/overlays/{dev,production}. They
include the source directories below and patch resources this repository
renders, by kind, name, JSON-pointer path and list index. A source change that
renames a patched resource, reorders a patched list or drops a patched field
would silently retarget a hosted patch, or break the hosted render only at
promotion. HOSTED_PATCH_CONTRACT names each patched resource and every path,
index and peer shape those patches rely on, so such a change fails here first.

The list mirrors those overlays and must change together with them. It never
reads them: they are not part of this repository.
"""

