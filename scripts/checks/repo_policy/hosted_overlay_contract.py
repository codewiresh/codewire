def name_pattern(kind: str, name: str) -> str:
    if kind == "ConfigMap" and name in GENERATED_CONFIG_MAPS:
        return rf"{re.escape(name)}-[a-z0-9]{{10}}"
    return re.escape(name)


def render_hosted_sources(work: Path) -> str:
    """Render every source directory the hosted overlays include, unpatched."""
    root = work / "sources"
    root.mkdir()
    resources = [
        os.path.relpath(ROOT / "deployments/k8s" / source, root)
        for source in HOSTED_OVERLAY_SOURCES
    ]
    (root / "kustomization.yaml").write_text(json.dumps({"resources": resources}), encoding="utf-8")
    return run(["kustomize", "build", "--load-restrictor", "LoadRestrictionsNone", str(root)]).stdout


def hosted_overlay_contract_failures(
    rendered: str, work: Path, only: tuple[str, str] | None = None
) -> list[str]:
    """Every contract failure, or only those of one (kind, name) entry."""
    failures: list[str] = []
    resources = documents(rendered)
    for image in HOSTED_IMAGES:
        if not re.search(rf"^\s*(?:- )?image: {re.escape(image)}(?:[:@]|$)", rendered, re.MULTILINE):
            failures.append(f"image {image}: no source workload uses it, so the hosted image pin rewrites nothing")

    probe = work / "probe"
    probe.mkdir(exist_ok=True)
    (probe / "rendered.yaml").write_text(rendered, encoding="utf-8")
    for kind, name, operations in HOSTED_PATCH_CONTRACT:
        if only is not None and (kind, name) != only:
            continue
        pattern = name_pattern(kind, name)
        matches = [
            resource
            for resource in resources
            if top_level_field(resource, "kind") == kind
            and re.fullmatch(pattern, metadata_field(resource, "name") or "")
        ]
        if len(matches) != 1:
            failures.append(
                f"{kind}/{name}: the hosted overlays patch exactly one source resource, found {len(matches)}"
            )
            continue
        if not operations:
            continue
        kustomization = {
            "resources": ["rendered.yaml"],
            "patches": [{"target": {"kind": kind, "name": pattern}, "patch": json.dumps(operations)}],
        }
        (probe / "kustomization.yaml").write_text(json.dumps(kustomization), encoding="utf-8")
        result = run(["kustomize", "build", str(probe)], check=False)
        if result.returncode != 0:
            detail = (result.stderr.strip() or result.stdout.strip() or f"exit {result.returncode}").splitlines()[0]
            failures.append(f"{kind}/{name}: a hosted overlay patch no longer applies: {detail.removeprefix('Error: ')}")
    return failures


def mutated(rendered: str, kind: str, name: str, old: str, new: str) -> str:
    pattern = name_pattern(kind, name)
    resources = documents(rendered)
    indexes = [
        index
        for index, resource in enumerate(resources)
        if top_level_field(resource, "kind") == kind
        and re.fullmatch(pattern, metadata_field(resource, "name") or "")
    ]
    if len(indexes) != 1 or resources[indexes[0]].count(old) != 1:
        raise RuntimeError(f"self-test fixture {kind}/{name} does not contain {old!r} exactly once")
    resources[indexes[0]] = resources[indexes[0]].replace(old, new)
    return "\n---\n".join(resources) + "\n"


