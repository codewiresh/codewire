def hosted_overlay_contract_self_test(rendered: str, work: Path) -> list[str]:
    problems: list[str] = []
    for label, kind, name, old, new, expected in SELF_TEST_MUTATIONS:
        # Each mutation changes one resource, so only its entry is evaluated.
        failures = hosted_overlay_contract_failures(
            mutated(rendered, kind, name, old, new), work, (kind, name)
        )
        if not any(expected in failure for failure in failures):
            problems.append(f"self-test {label}: expected a failure containing {expected!r}; got {failures!r}")
    return problems


def check_hosted_overlay_contract(args: argparse.Namespace) -> int:
    with tempfile.TemporaryDirectory(prefix="hosted-overlay-contract-") as directory:
        work = Path(directory)
        try:
            rendered = render_hosted_sources(work)
            failures = hosted_overlay_contract_failures(rendered, work)
            if not failures and args.self_test:
                failures = hosted_overlay_contract_self_test(rendered, work)
        except Exception as error:  # noqa: BLE001 - repository policy boundary
            failures = [str(error)]
    if failures:
        for failure in failures:
            print(f"::error::hosted overlay contract: {failure}", file=sys.stderr)
        return 1
    suffix = "; mutations rejected" if args.self_test else ""
    print(f"hosted overlay contract: OK ({len(HOSTED_PATCH_CONTRACT)} patched resource(s)){suffix}")
    return 0
