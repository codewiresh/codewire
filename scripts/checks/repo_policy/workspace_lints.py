"""Every workspace crate takes the workspace lints, and their allows only shrink.

`[workspace.lints]` in Cargo.toml sets the clippy levels, and a crate gets
them only when its manifest says `[lints] workspace = true`. A crate that
leaves the line out is linted at clippy's defaults and nothing says so. This
check fails that crate. A curated image workspace (deployments/docker) builds
the same crates, so it must define the table its members inherit.

The lints below were turned on over code that predates them. Each crate root
that did not pass carries a crate-level allow, and DEBT is the list of those
files (#4125). The list only shrinks: a file outside it that names one of the
lints fails, and so does a listed file that no longer does. `unwrap_used` is
also allowed in integration tests, examples and benches, where clippy's
`allow-unwrap-in-tests` does not reach.
"""

from __future__ import annotations

from .shared import *

# Generated by cargo-hakari and holds no code.
GENERATED_MEMBERS = ("crates/codewire-workspace-hack",)
CURATED_MANIFEST = re.compile(r"^deployments/docker/[A-Za-z0-9_-]+\.Cargo\.toml$")
TEST_SOURCE = re.compile(r"^crates/[^/]+/(?:tests|examples|benches)/")
ALLOWED_IN_TESTS = ("clippy::unwrap_used",)

DEBT: dict[str, tuple[str, ...]] = {
    "clippy::undocumented_unsafe_blocks": (
        "crates/codewire-cli/src/lib.rs",
        "crates/codewire-daemon/src/lib.rs",
        "crates/codewire-local-vmm/src/lib.rs",
        "crates/codewire-local-vmm/tests/network_worker_process.rs",
        "crates/codewire-vmm-guest-probe/src/lib.rs",
        "crates/codewire-vmm-guest-probe/tests/cw-runtime-live.rs",
    ),
    "clippy::unwrap_used": (
        "crates/codewire-cli/src/lib.rs",
        "crates/codewire-credential-broker/src/lib.rs",
        "crates/codewire-credential-service/src/lib.rs",
        "crates/codewire-cw-release/src/lib.rs",
        "crates/codewire-daemon/src/lib.rs",
        "crates/codewire-local-credentials/src/lib.rs",
        "crates/codewire-local-vmm/src/lib.rs",
        "crates/codewire-mesh/src/lib.rs",
        "crates/codewire-netstack/src/lib.rs",
        "crates/codewire-orchestration/src/lib.rs",
        "crates/codewire-tailnet/src/lib.rs",
        "crates/codewire-vmm-guest-probe/src/lib.rs",
        "crates/codewire-workload-secrets/src/lib.rs",
        "crates/codewire-workspace-access/src/lib.rs",
    ),
}


def member_failures(manifests: dict[str, dict[str, Any]]) -> list[str]:
    """`manifests` maps each tracked Cargo manifest path to its parsed table."""
    failures: list[str] = []
    members = manifests["Cargo.toml"].get("workspace", {}).get("members", [])
    for member in members:
        if member in GENERATED_MEMBERS:
            continue
        path = f"{member}/Cargo.toml"
        if manifests.get(path, {}).get("lints", {}).get("workspace") is not True:
            failures.append(f"{path} must set `[lints] workspace = true`")
    for path, manifest in sorted(manifests.items()):
        if CURATED_MANIFEST.match(path) and "lints" not in manifest.get("workspace", {}):
            failures.append(f"{path} must define `[workspace.lints]` for its members to inherit")
    return failures


def allow_failures(sources: dict[str, str], debt: dict[str, tuple[str, ...]]) -> list[str]:
    """`sources` maps each tracked Rust file under crates/ to its text."""
    failures: list[str] = []
    for lint, listed in debt.items():
        for path, text in sorted(sources.items()):
            if lint not in text or path in listed:
                continue
            if lint in ALLOWED_IN_TESTS and TEST_SOURCE.match(path):
                continue
            failures.append(
                f"{path} names {lint}: fix the code instead; the allow list only shrinks"
            )
        for path in listed:
            if lint not in sources.get(path, ""):
                failures.append(f"{path} no longer allows {lint}: remove it from DEBT")
    return failures


def self_test() -> list[str]:
    failures: list[str] = []

    def expect(name: str, actual: list[str], wanted: list[str]) -> None:
        if actual != wanted:
            failures.append(f"workspace lints self-test: {name} gave {actual!r}")

    root = {"workspace": {"members": ["crates/a", "crates/codewire-workspace-hack"], "lints": {}}}
    opted_in = {"lints": {"workspace": True}}
    expect("an opted-in workspace", member_failures({"Cargo.toml": root, "crates/a/Cargo.toml": opted_in}), [])
    for name, manifest in (("no table", {}), ("its own table", {"lints": {"clippy": {}}}),
                           ("workspace = false", {"lints": {"workspace": False}})):
        expect(f"a member with {name}", member_failures({"Cargo.toml": root, "crates/a/Cargo.toml": manifest}),
               ["crates/a/Cargo.toml must set `[lints] workspace = true`"])
    curated = "deployments/docker/derp.Cargo.toml"
    expect("a curated workspace with the table",
           member_failures({"Cargo.toml": root, "crates/a/Cargo.toml": opted_in, curated: {"workspace": {"lints": {}}}}), [])
    expect("a curated workspace without the table",
           member_failures({"Cargo.toml": root, "crates/a/Cargo.toml": opted_in, curated: {"workspace": {}}}),
           [f"{curated} must define `[workspace.lints]` for its members to inherit"])

    unwrap, unsafe = "clippy::unwrap_used", "clippy::undocumented_unsafe_blocks"
    debt = {unsafe: ("crates/a/src/lib.rs",), unwrap: ()}
    lib = f"#![allow({unsafe})]\n"
    expect("a listed root", allow_failures({"crates/a/src/lib.rs": lib}, debt), [])
    expect("an unlisted root", allow_failures({"crates/a/src/lib.rs": lib, "crates/b/src/lib.rs": lib}, debt),
           [f"crates/b/src/lib.rs names {unsafe}: fix the code instead; the allow list only shrinks"])
    expect("an item-level allow", allow_failures({"crates/a/src/lib.rs": lib, "crates/a/src/x.rs": f"#[allow({unwrap})]\n"}, debt),
           [f"crates/a/src/x.rs names {unwrap}: fix the code instead; the allow list only shrinks"])
    expect("a cleaned root still listed", allow_failures({"crates/a/src/lib.rs": ""}, debt),
           [f"crates/a/src/lib.rs no longer allows {unsafe}: remove it from DEBT"])
    tests = {"crates/a/src/lib.rs": lib, "crates/a/tests/flow.rs": f"#![allow({unwrap})]\n"}
    expect("unwrap in an integration test", allow_failures(tests, debt), [])
    tests["crates/a/tests/flow.rs"] = f"#![allow({unsafe})]\n"
    expect("undocumented unsafe in an integration test", allow_failures(tests, debt),
           [f"crates/a/tests/flow.rs names {unsafe}: fix the code instead; the allow list only shrinks"])
    return failures


def check_workspace_lints(args: argparse.Namespace) -> int:
    if args.self_test:
        if report("workspace lints", self_test()):
            return 1
        print("workspace lints: OK (self-test)")
        return 0
    files = git_source_files()
    manifests = {
        path: tomllib.loads(read_text(path))
        for path in files
        if path == "Cargo.toml" or CURATED_MANIFEST.match(path) or re.fullmatch(r"crates/[^/]+/Cargo\.toml", path)
    }
    sources = {
        path: read_text(path) for path in files if path.startswith("crates/") and path.endswith(".rs")
    }
    failures = member_failures(manifests) + allow_failures(sources, DEBT)
    if report("workspace lints", failures):
        return 1
    listed = sum(len(paths) for paths in DEBT.values())
    print(f"workspace lints: OK ({len(manifests)} manifests, {listed} allows left)")
    return 0
