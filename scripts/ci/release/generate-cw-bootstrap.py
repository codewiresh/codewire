#!/usr/bin/env python3
"""Deterministically embed the shared release consumer closure and public trust."""

import argparse
import ast
from pathlib import Path


SHARED_NAMES = (
    "PAYLOAD_SCHEMA_VERSION", "PROTOCOL_VERSION", "RECORD_VERSION", "MIN_EXECUTABLE",
    "MAX_EXECUTABLE", "MAX_JSON", "MAX_SIGNATURE", "RELEASE_TARGETS", "RUNTIME_TARGET",
    "OBJECT_PREFIX", "RELEASE_SCHEMA", "CHANNEL_SCHEMA", "CHANNELS", "PRODUCTION_FINGERPRINT",
    "BUILD_RECORD_MAGIC", "BUILD_RECORD_FIELDS", "MAX_BUILD_RECORD", "ReleaseError", "require",
    "sha256", "is_hex", "exact", "canonical", "_unique", "parse_json", "parse_canonical",
    "read_regular", "write_new", "blob_key", "release_key", "channel_key", "valid_version",
    "release_version", "check_header", "check_static_elf", "valid_rustc", "build_record",
    "validate_identity", "make_identity", "object_ref", "asset_name", "validate_ref",
    "validate_manifest", "Trust", "verify_detached", "validate_pointer", "verify_channel",
    "check_signed_release",
)


def named_nodes(text):
    found = {}
    for node in ast.parse(text).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            found[node.name] = node
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            found[node.targets[0].id] = node
    return found


def render(shared, consumer, key):
    nodes = named_nodes(shared)
    closure = "\n\n".join(ast.get_source_segment(shared, nodes[name]) for name in SHARED_NAMES)
    consumer = consumer.replace("import cw_release as release", "release = sys.modules[__name__]", 1)
    node = named_nodes(consumer)["production_key_bytes"]
    start, end = node.lineno - 1, node.end_lineno
    lines = consumer.splitlines(keepends=True)
    lines[start:end] = ["def production_key_bytes():\n", f"    return {key!r}\n"]
    consumer = "".join(lines)
    wrapper = """#!/usr/bin/env bash
# Generated by scripts/ci/release/generate-cw-bootstrap.py. Edit the inputs.
set -euo pipefail
command -v python3 >/dev/null 2>&1 || {
  printf '%s\\n' 'cw install: Python3 is required; install Python3 and retry' >&2
  exit 1
}
exec python3 -I -B - "$@" <<'CW_BOOTSTRAP_PY'
import hashlib, json, os, re, stat, struct, subprocess, tempfile
from pathlib import Path

"""
    return wrapper + closure + "\n\n" + consumer + "\nCW_BOOTSTRAP_PY\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    rendered = render((root / "scripts/ci/release/cw_release.py").read_text(),
                      (root / "scripts/ci/release/cw_bootstrap.py").read_text(),
                      (root / "apps/cli/GPG_PUBLIC_KEY.asc").read_bytes())
    output = root / "apps/cli/install.sh"
    if args.check:
        if output.read_text() != rendered:
            parser.exit(1, "cw bootstrap generation drift; regenerate apps/cli/install.sh\n")
    else:
        output.write_text(rendered)


if __name__ == "__main__":
    main()
