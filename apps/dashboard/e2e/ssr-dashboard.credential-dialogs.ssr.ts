test("dirty private inputs survive Keep editing, Escape and backdrop until explicit Discard", async ({ page }) => {
  let posts = 0;
  page.on("request", (request) => { if (request.method() === "POST") posts += 1; });
  await page.getByRole("button", { name: "Add credential", exact: true }).click();
  await page.getByRole("dialog", { name: "Add credential", exact: true }).getByRole("button", { name: "API key", exact: true }).click();
  const api = page.getByRole("dialog", { name: "Add API key", exact: true });
  const key = api.getByLabel("API key", { exact: true });
  await key.fill("synthetic-kept-private-value");
  const form = page.locator("#add-api-key form");
  await form.locator('[name="_csrf"]').evaluate((control: HTMLInputElement) => { control.value = "fresh-csrf-fence"; });
  await page.keyboard.press("Escape");
  const prompt = page.getByRole("dialog", { name: "Discard changes?", exact: true });
  await expect(prompt.getByRole("button", { name: "Keep editing", exact: true })).toBeFocused();
  await page.screenshot({ path: test.info().outputPath("discard-changes-dialog.png") });
  await expect(api).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(prompt).not.toBeVisible();
  await expect(key).toBeFocused();
  await expect(key).toHaveValue("synthetic-kept-private-value");
  await api.getByRole("button", { name: "Cancel", exact: true }).click();
  await prompt.getByRole("button", { name: "Keep editing", exact: true }).click();
  await expect(api.getByRole("button", { name: "Cancel", exact: true })).toBeFocused();
  await page.mouse.click(2, 2);
  await expect(prompt).toBeVisible();
  await page.mouse.click(2, 2);
  await expect(prompt).not.toBeVisible();
  await expect(key).toHaveValue("synthetic-kept-private-value");
  await api.getByRole("button", { name: "Cancel", exact: true }).click();
  await prompt.getByRole("button", { name: "Discard changes", exact: true }).click();
  await expect(api).not.toBeVisible();
  await expect(page.locator("#api-key-value")).toHaveValue("");
  expect(await form.locator('[name="_csrf"]').inputValue()).toBe("fresh-csrf-fence");
  expect(posts).toBe(0);
});

test("untouched and reverted selects close without warnings and Discard restores native defaults", async ({ page }) => {
  const add = page.getByRole("button", { name: "Add credential", exact: true });
  const chooser = page.getByRole("dialog", { name: "Add credential", exact: true });
  const api = page.getByRole("dialog", { name: "Add API key", exact: true });
  const prompt = page.getByRole("dialog", { name: "Discard changes?", exact: true });
  await add.click();
  await chooser.getByRole("button", { name: "API key", exact: true }).click();
  const provider = api.getByRole("combobox", { name: "Provider", exact: true });
  const initial = await provider.inputValue();
  await api.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(api).not.toBeVisible();
  await expect(prompt).not.toBeVisible();
  await add.click();
  await chooser.getByRole("button", { name: "API key", exact: true }).click();
  await provider.selectOption("anthropic");
  await provider.selectOption(initial);
  await page.keyboard.press("Escape");
  await expect(api).not.toBeVisible();
  await expect(prompt).not.toBeVisible();
  await add.click();
  await chooser.getByRole("button", { name: "API key", exact: true }).click();
  await provider.selectOption("anthropic");
  await page.keyboard.press("Escape");
  await expect(prompt).toBeVisible();
  await prompt.getByRole("button", { name: "Discard changes", exact: true }).click();
  await add.click();
  await chooser.getByRole("button", { name: "API key", exact: true }).click();
  await expect(provider).toHaveValue(initial);
  await api.getByRole("button", { name: "Cancel", exact: true }).click();
  await add.click();
  await chooser.getByRole("button", { name: "SSH identity", exact: true }).click();
  const ssh = page.getByRole("dialog", { name: "Add SSH identity", exact: true });
  await ssh.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(ssh).not.toBeVisible();
  await expect(prompt).not.toBeVisible();
});

test("Discard clears reconnect consent and preserves hidden concurrency fences", async ({ page }) => {
  const opener = page.getByRole("button", { name: "Manage verified-user", exact: true });
  await opener.click();
  const manage = page.getByRole("dialog", { name: "Manage verified-user", exact: true });
  await manage.locator("details").filter({ has: page.locator("summary", { hasText: "Reconnect GitHub App" }) }).locator(":scope > summary").click();
  const consent = manage.getByRole("checkbox", { name: "I understand this reconnect may reactivate the credential.", exact: true });
  await consent.check();
  await manage.getByRole("button", { name: "Close", exact: true }).click();
  const prompt = page.getByRole("dialog", { name: "Discard changes?", exact: true });
  await prompt.getByRole("button", { name: "Keep editing", exact: true }).click();
  await expect(consent).toBeChecked();
  await manage.getByRole("button", { name: "Close", exact: true }).click();
  await prompt.getByRole("button", { name: "Discard changes", exact: true }).click();
  await opener.click();
  await expect(consent).not.toBeChecked();
  await manage.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: "Edit profile", exact: true }).click();
  const edit = page.getByRole("dialog", { name: "Edit work", exact: true });
  await edit.locator('[name="expected_revision"]').evaluate((control: HTMLInputElement) => { control.value = "8"; });
  await edit.getByRole("combobox", { name: "GitHub", exact: true }).selectOption("");
  await edit.getByRole("button", { name: "Cancel", exact: true }).click();
  await prompt.getByRole("button", { name: "Discard changes", exact: true }).click();
  await page.getByRole("button", { name: "Edit profile", exact: true }).click();
  await expect(edit.locator('[name="expected_revision"]')).toHaveValue("8");
  await expect(edit.getByRole("combobox", { name: "GitHub", exact: true })).toHaveValue("fixture-github");
});
